'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';
import { ReactNode } from 'react';

export interface NavItem {
  href: string;
  label: string;
  icon: ReactNode;
  badge?: string | number;
}

interface SidebarProps {
  items: NavItem[];
  isOpen: boolean;
  onToggle: () => void;
  title?: string;
}

export function Sidebar({ items, isOpen, onToggle, title = 'Navigation' }: SidebarProps) {
  const pathname = usePathname();

  const isActive = (href: string) => pathname === href || pathname?.startsWith(href + '/');

  return (
    <>
      {/* Mobile overlay */}
      {isOpen && (
        <div
          className="fixed inset-0 bg-black/50 z-40 lg:hidden"
          onClick={onToggle}
          aria-hidden="true"
        />
      )}

      {/* Sidebar */}
      <aside
        className={`fixed top-0 left-0 z-40 h-full w-64 bg-white border-r border-gray-200 transform transition-transform duration-300 ease-in-out lg:translate-x-0 lg:static lg:z-0 ${
          isOpen ? 'translate-x-0' : '-translate-x-full'
        }`}
      >
        {/* Sidebar Header */}
        <div className="flex items-center justify-between h-16 px-4 border-b border-gray-200 lg:hidden">
          <span className="text-lg font-semibold text-gray-800">{title}</span>
          <button
            onClick={onToggle}
            className="p-2 rounded-md text-gray-600 hover:text-[#C75B39] hover:bg-gray-100 transition-colors"
            aria-label="Close sidebar"
          >
            <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Desktop title */}
        <div className="hidden lg:flex items-center h-16 px-4 border-b border-gray-200">
          <span className="text-lg font-semibold text-gray-800">{title}</span>
        </div>

        {/* Navigation Items */}
        <nav className="px-3 py-4 space-y-1 overflow-y-auto h-[calc(100%-4rem)]">
          {items.map((item) => (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center justify-between px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                isActive(item.href)
                  ? 'bg-[#C75B39]/10 text-[#C75B39]'
                  : 'text-gray-700 hover:bg-gray-100 hover:text-[#C75B39]'
              }`}
              onClick={() => {
                // Close sidebar on mobile when navigating
                if (window.innerWidth < 1024) {
                  onToggle();
                }
              }}
            >
              <div className="flex items-center gap-3">
                <span
                  className={`flex-shrink-0 ${
                    isActive(item.href) ? 'text-[#C75B39]' : 'text-gray-500'
                  }`}
                >
                  {item.icon}
                </span>
                <span>{item.label}</span>
              </div>
              {item.badge !== undefined && (
                <span
                  className={`px-2 py-0.5 text-xs font-medium rounded-full ${
                    isActive(item.href)
                      ? 'bg-[#C75B39] text-white'
                      : 'bg-gray-200 text-gray-600'
                  }`}
                >
                  {item.badge}
                </span>
              )}
            </Link>
          ))}
        </nav>
      </aside>
    </>
  );
}

